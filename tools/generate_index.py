"""Generate the document catalog, or check its freshness without writing files."""
import argparse
from pathlib import Path
import sys
from urllib.parse import quote

if __package__:
    from .audit_zta import audit, render_report
    from .document_metadata import DOCUMENT_TYPES, frontmatter
else:
    from audit_zta import audit, render_report
    from document_metadata import DOCUMENT_TYPES, frontmatter


INDEX_METADATA = dict(
    schema_version=1, id='DOC-ZTA-INDEX', title='Document index',
    document_type='navigation', parent='ROOT', lineage=['ROOT'],
    owner='Documentation Engineering', owner_status='proposed',
    document_status='draft', implementation_status='not-applicable',
    baseline_date='2026-10-25',
)


def escape(value):
    return str(value).replace('\\', '\\\\').replace('|', '\\|').replace('[', '\\[').replace(']', '\\]')


def render_index(result):
    """Use auditor discovery so exclusions and metadata have one interpretation."""
    lines = [frontmatter(INDEX_METADATA).rstrip(), '', '# Document index', '',
             'Generated by `python3 tools/generate_index.py --root .`. Edit document frontmatter, then regenerate this file.', '',
             'Start with the [README](README.md), [project guide](zta-project-guide.md), or [visual taxonomy](taxonomy.md). '
             'Document status describes editorial maturity; it does not validate architecture or equipment.', '']
    metadata = dict(result.metadata)
    metadata[result.root / 'index.md'] = INDEX_METADATA
    for kind in DOCUMENT_TYPES:
        entries = sorted(((path, data) for path, data in metadata.items() if data['document_type'] == kind),
                         key=lambda item: item[0].relative_to(result.root).as_posix())
        if not entries:
            continue
        lines += [f'## {kind.capitalize()}', '', '| Document | ID | Owner (ownership status) | Document status |',
                  '|---|---|---|---|']
        for path, data in entries:
            link = quote(path.relative_to(result.root).as_posix(), safe='/')
            lines.append(f'| [{escape(data["title"])}]({link}) | {data["id"]} | '
                         f'{escape(data["owner"])} ({data["owner_status"]}) | {data["document_status"]} |')
        lines.append('')
    lines += ['## Imported source documents', '',
              'Preserved source material is excluded from metadata and internal-link auditing. '
              'Its examples do not declare project entities.', '']
    for relative in result.excluded:
        if relative != 'audit-report.md':
            lines.append(f'- [{escape(relative)}]({quote(relative, safe="/")})')
    lines += ['', '## Generated reports', '',
              '`audit-report.md` is local generated output, excluded from source auditing and version control. '
              'Create it with the auditor; it may be absent in a fresh checkout.', '']
    return '\n'.join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path('.'))
    parser.add_argument('--check', action='store_true', help='Fail if index.md is missing or stale')
    args = parser.parse_args(argv)
    result = audit(args.root)
    # Regeneration must repair a stale/corrupt generated body and bootstrap a
    # missing index, even when source documents already link to that index.
    index_path = result.root / 'index.md'
    def generated_issue(issue):
        if issue.path == index_path:
            return True
        if not index_path.exists() and issue.code == 'broken-link' and issue.message.startswith('Missing target: '):
            destination = issue.message.removeprefix('Missing target: ').split('#', 1)[0]
            return (issue.path.parent / destination).resolve() == index_path
        return False
    result.issues = [issue for issue in result.issues if not generated_issue(issue)]
    for path, data in result.metadata.items():
        if path != index_path and data['id'] == INDEX_METADATA['id']:
            result.error(path, 1, 'duplicate-id', f'{data["id"]} is reserved for index.md')
    if result.issues:
        print(render_report(result), end='')
        return 1
    expected = render_index(result)
    path = result.root / 'index.md'
    try:
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != expected:
                print('index.md is missing or stale; run python3 tools/generate_index.py --root .')
                return 1
            print('PASS: index.md is current')
        else:
            path.write_text(expected, encoding='utf-8')
            print('Updated index.md')
    except (OSError, UnicodeError) as exc:
        print(f'Cannot access index.md: {exc}', file=sys.stderr)
        return 2
    return 0


if __name__ == '__main__':
    sys.exit(main())
